gp_model_execute_import_context <- function(ctx) {
  if (is.null(ctx)) {
    ctx <- list()
  }
  context_names <- gp_model_execute_route_context_variables()
  defaults <- stats::setNames(
    rep(list(NULL), length(context_names)),
    context_names
  )
  list2env(utils::modifyList(defaults, ctx, keep.null = TRUE), envir = parent.frame())
  invisible(NULL)
}
